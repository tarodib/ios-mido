static int row, col;
static uint8_t bg_r, bg_g, bg_b;
static uint32_t log_len;

static void px(int x, int y, uint8_t r, uint8_t g, uint8_t b)
{
	volatile uint8_t *p = (volatile uint8_t *)(FB_PHYS + (uintptr_t)y * STRIDE + (uintptr_t)x * 3);
	p[0] = b; p[1] = g; p[2] = r;
}

void con_clear(uint32_t rgb)
{
	bg_r = rgb >> 16; bg_g = rgb >> 8; bg_b = rgb;
	uint8_t p[12];
	for (int i = 0; i < 12; i += 3) { p[i] = bg_b; p[i + 1] = bg_g; p[i + 2] = bg_r; }
	uint32_t w[3];
	for (int i = 0; i < 3; i++)
		w[i] = p[4*i] | p[4*i+1] << 8 | p[4*i+2] << 16 | (uint32_t)p[4*i+3] << 24;
	for (uintptr_t a = FB_PHYS; a < FB_PHYS + (uintptr_t)STRIDE * FB_H; a += 12) {
		*(volatile uint32_t *)a = w[0];
		*(volatile uint32_t *)(a + 4) = w[1];
		*(volatile uint32_t *)(a + 8) = w[2];
	}
	row = col = 0;
}

static void log_putc(char c)
{
	if (log_len + 16 < LOG_SIZE) {
		*(volatile char *)(LOG_PHYS + 16 + log_len) = c;
		log_len++;
		*(volatile uint32_t *)(LOG_PHYS + 8) = log_len;
	}
}

uintptr_t con_log_phys(void)
{
	return LOG_PHYS;
}

void con_log_init(void)
{
	/* header: "MIDOSHIM" magic + u32 length, text from +16 */
	const char m[] = "MIDOSHIM";
	for (int i = 0; i < 8; i++)
		*(volatile char *)(LOG_PHYS + i) = m[i];
	log_len = 0;
	*(volatile uint32_t *)(LOG_PHYS + 8) = 0;
}

static void draw(char c, int cx, int cy)
{
	if (c >= 'a' && c <= 'z')
		c -= 32;
	int gi = -1;
	for (int i = 0; glyph_chars[i]; i++)
		if (glyph_chars[i] == c) { gi = i; break; }
	for (int gy = 0; gy < 8; gy++)
		for (int gx = 0; gx < 6; gx++) {
			int on = gi >= 0 && gy < 7 && gx < 5 && (glyphs[gi][gy] >> (4 - gx)) & 1;
			for (int sy = 0; sy < SCALE; sy++)
				for (int sx = 0; sx < SCALE; sx++)
					px(cx * CELL_W + gx * SCALE + sx, cy * CELL_H + gy * SCALE + sy,
					   on ? 0xff : bg_r, on ? 0xff : bg_g, on ? 0xff : bg_b);
		}
}

void con_putc(char c)
{
	log_putc(c);
	if (c == '\n') { row++; col = 0; }
	else {
		if (col >= COLS) { row++; col = 0; }
		if (row < ROWS)
			draw(c, col, row);
		col++;
	}
}

void con_puts(const char *s)
{
	while (*s)
		con_putc(*s++);
}

void con_hex(uint64_t v, int digits)
{
	for (int i = digits - 1; i >= 0; i--)
		con_putc("0123456789ABCDEF"[(v >> (i * 4)) & 0xf]);
}

void con_dec(uint64_t v)
{
	char b[21];
	int n = 0;
	do { b[n++] = '0' + v % 10; v /= 10; } while (v);
	while (n)
		con_putc(b[--n]);
}

/* "LABEL  0x...." on its own line */
void con_kv(const char *k, uint64_t v)
{
	con_puts(k);
	con_puts("=");
	con_hex(v, v >> 32 ? 16 : 8);
	con_putc('\n');
}
