/*
 * Text console on the LK continuous-splash framebuffer.
 * Format (measured in M1): 1080x1920, 24bpp, byte order B,G,R, stride 3240.
 * Font: original 5x7 bitmap, drawn at 4x scale in a 6x8 cell -> 45x60 chars.
 * Every line is also appended to a plain-text log at LOG_PHYS. That is inside
 * the no-map wcnss_fw_region (0x8E700000+7M): Linux never maps or clears it
 * and recovery never starts Wi-Fi, so after a warm reset OrangeFox can read
 * it via /dev/mem (tools/shimlog.ps1). pstore (0x9FF00000) is NOT usable:
 * the kernel's ramoops wipes buffers without a valid ramoops signature.
 */
#include <stdint.h>
#include "console.h"

#define FB_PHYS  0x90001000UL
#define FB_W     1080
#define FB_H     1920
#define STRIDE   (FB_W * 3)
#define SCALE    4
#define CELL_W   (6 * SCALE)
#define CELL_H   (8 * SCALE)
#define COLS     (FB_W / CELL_W)
#define ROWS     (FB_H / CELL_H)

#define LOG_PHYS 0x8ec00000UL
#define LOG_SIZE 0x10000UL

